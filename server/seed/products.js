async function seedProducts() {
  await connectDatabase();
  await migrateLegacyProductCategories();

  const adminUser = await User.findOne({ email: 'admin@lumora.local' }).lean();
  const beautySeed = beautyProducts.map(({ id, _id, slug, createdAt, ...product }) => product);
  const shoppingSeed = shoppingProducts.map(({ id, _id, slug, group, listingRoute, route, isNew, createdAt, ...product }) => product);
  const payload = [...productSeed, ...beautySeed, ...shoppingSeed].map((product) => ({
    ...product,
    createdBy: adminUser?._id || undefined,
    stock: product.stock ?? 10,
    rating: product.rating ?? 4.5,
    imageUrl: product.imageUrl,
    images: product.images || [product.imageUrl],
    brand: product.brand || 'Lumora',
    discount: product.discount ?? 0,
    originalPrice: product.originalPrice || product.price,
  }));

  await Product.bulkWrite(payload.map((product) => ({
    updateOne: {
      filter: {
        department: product.department,
        category: product.category,
        subcategory: product.subcategory,
        name: product.name,
      },
      update: { $set: product },
      upsert: true,
    },
  })));
  console.log(`Seeded or updated ${payload.length} products.`);
}

seedProducts()
  .then(() => process.exit(0))
  .catch((error) => {
    console.error('Failed to seed products:', error);
    process.exit(1);
  });
